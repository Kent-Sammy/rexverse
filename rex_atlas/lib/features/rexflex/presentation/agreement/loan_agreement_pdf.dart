import 'dart:typed_data';

import 'package:flutter/services.dart' show rootBundle;
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../../../core/formatting/dates.dart';
import '../../../../core/formatting/naira.dart';
import '../../domain/rexflex_models.dart';

/// Builds the RexFlex loan agreement as a PDF from the loan's real details.
///
/// The legal wording is prototype copy and the document is stamped DEMO on
/// every page: the binding agreement text must come from Rex Legal.
Future<Uint8List> buildLoanAgreementPdf({
  required FlexLoan loan,
  required String borrowerName,
  required String accountLabel,
  PdfPageFormat format = PdfPageFormat.a4,
  bool compress = true,
}) async {
  Future<pw.Font> font(String file) async =>
      pw.Font.ttf(await rootBundle.load('assets/fonts/$file'));
  final regular = await font('Inter-Regular.ttf');
  final semibold = await font('Inter-SemiBold.ttf');
  final bold = await font('Inter-Bold.ttf');

  const navy = PdfColor.fromInt(0xFF002766);
  const grey = PdfColor.fromInt(0xFF5B6475);
  const panel = PdfColor.fromInt(0xFFEFF4FF);
  const amber = PdfColor.fromInt(0xFFFFF1DC);
  const amberText = PdfColor.fromInt(0xFF5B4A1F);

  final start = loan.startDate ?? loan.appliedAt;
  final due = loan.dueDate ?? loan.proposedDueDate;
  final accepted = loan.appliedAt;

  pw.TextStyle st(
    double size, {
    pw.Font? f,
    PdfColor color = PdfColors.black,
  }) => pw.TextStyle(
    font: f ?? regular,
    fontSize: size,
    color: color,
    lineSpacing: 2,
  );

  pw.Widget heading(String n, String title) => pw.Padding(
    padding: const pw.EdgeInsets.only(top: 14, bottom: 4),
    child: pw.Text(
      '$n. $title',
      style: st(11, f: semibold, color: navy),
    ),
  );
  pw.Widget para(String text) => pw.Padding(
    padding: const pw.EdgeInsets.only(bottom: 4),
    child: pw.Text(text, style: st(9.5), textAlign: pw.TextAlign.justify),
  );

  final rows = <(String, String)>[
    ('Agreement reference', loan.id),
    ('Loan amount (principal)', Naira.grouped(loan.principalKobo)),
    ('Interest', Naira.grouped(loan.interestKobo)),
    ('Total amount repayable', Naira.grouped(loan.totalKobo)),
    ('Tenor', '${loan.term.days} days'),
    ('Disbursement date', RexDates.dayMonthYear(start)),
    ('Due date', RexDates.dayMonthYear(due)),
    ('Repayment account', accountLabel),
  ];

  final doc = pw.Document(
    compress: compress,
    title: 'RexFlex Loan Agreement ${loan.id}',
    author: 'Rex',
    subject: 'Demo loan agreement',
  );

  doc.addPage(
    pw.MultiPage(
      pageFormat: format,
      margin: const pw.EdgeInsets.fromLTRB(40, 36, 40, 40),
      header: (_) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.stretch,
        children: [
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text(
                'Rex',
                style: st(20, f: bold, color: navy),
              ),
              pw.Text(
                'RexFlex Loan Agreement',
                style: st(12, f: semibold, color: navy),
              ),
            ],
          ),
          pw.SizedBox(height: 8),
          pw.Container(
            padding: const pw.EdgeInsets.symmetric(vertical: 5, horizontal: 8),
            decoration: const pw.BoxDecoration(
              color: amber,
              borderRadius: pw.BorderRadius.all(pw.Radius.circular(4)),
            ),
            child: pw.Text(
              'DEMO DOCUMENT · generated by the Rex prototype · not a binding '
              'agreement and no money has moved',
              style: st(8, f: semibold, color: amberText),
              textAlign: pw.TextAlign.center,
            ),
          ),
          pw.SizedBox(height: 12),
        ],
      ),
      footer: (ctx) => pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text('Ref ${loan.id}', style: st(8, color: grey)),
          pw.Text(
            'Page ${ctx.pageNumber} of ${ctx.pagesCount}',
            style: st(8, color: grey),
          ),
        ],
      ),
      build: (_) => [
        para(
          'This Loan Agreement is made on ${RexDates.dayMonthYear(accepted)} '
          'between Rex ("the Lender") and $borrowerName ("the Borrower"), '
          'holder of the Rex account $accountLabel.',
        ),
        pw.SizedBox(height: 8),
        pw.Container(
          padding: const pw.EdgeInsets.all(12),
          decoration: const pw.BoxDecoration(
            color: panel,
            borderRadius: pw.BorderRadius.all(pw.Radius.circular(6)),
          ),
          child: pw.Column(
            children: [
              pw.Align(
                alignment: pw.Alignment.centerLeft,
                child: pw.Text(
                  'Loan summary',
                  style: st(11, f: semibold, color: navy),
                ),
              ),
              pw.SizedBox(height: 6),
              for (final (k, v) in rows)
                pw.Padding(
                  padding: const pw.EdgeInsets.symmetric(vertical: 3),
                  child: pw.Row(
                    children: [
                      pw.Expanded(
                        child: pw.Text(k, style: st(9.5, color: grey)),
                      ),
                      pw.Text(v, style: st(9.5, f: semibold)),
                    ],
                  ),
                ),
            ],
          ),
        ),
        heading('1', 'The loan'),
        para(
          'The Lender agrees to lend the Borrower the principal stated in the '
          'loan summary, paid into the Borrower\'s Rex account on the '
          'disbursement date.',
        ),
        heading('2', 'Interest and charges'),
        para(
          'The Borrower will pay the interest stated in the loan summary for '
          'the tenor chosen. The total amount repayable is shown above and '
          'was displayed before the Borrower accepted. No other fees apply to '
          'this loan.',
        ),
        heading('3', 'Repayment'),
        para(
          'The Borrower will repay the total amount repayable on or before '
          'the due date from the Rex account above. The Borrower may repay in '
          'full or in parts at any time before the due date, without any '
          'early repayment charge.',
        ),
        heading('4', 'Late or missed repayment'),
        para(
          'If the loan is not repaid by the due date, the Lender may contact '
          'the Borrower and apply the measures set out in the RexFlex Credit '
          'Policy in force at the time.',
        ),
        heading('5', 'Credit assessment and data'),
        para(
          'The Borrower consents to the Lender using their Rex account data '
          'to assess eligibility for this and future loans. Each new loan '
          'requires a fresh eligibility and risk assessment.',
        ),
        heading('6', 'Future offers'),
        para(
          'Repaying on time may increase future offers, ordinarily up to '
          'twice the highest fully repaid principal. Future offers are not '
          'guaranteed.',
        ),
        heading('7', 'Acceptance'),
        para(
          'The Borrower accepted this agreement electronically in the Rex app '
          'on ${RexDates.dateTime(accepted)}.',
        ),
        pw.SizedBox(height: 18),
        pw.Row(
          children: [
            pw.Expanded(
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('Borrower', style: st(8, color: grey)),
                  pw.Text(borrowerName, style: st(10, f: semibold)),
                  pw.Text('Accepted electronically', style: st(8, color: grey)),
                ],
              ),
            ),
            pw.Expanded(
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('Lender', style: st(8, color: grey)),
                  pw.Text('Rex', style: st(10, f: semibold)),
                  pw.Text('RexFlex', style: st(8, color: grey)),
                ],
              ),
            ),
          ],
        ),
      ],
    ),
  );
  return doc.save();
}
